-- Airlines that a flight can be matched to. This is reference data: a flight still
-- stores the airline as text, so one that is missing here can be typed in as before.
CREATE TABLE airlines (
    -- Two-character IATA designator, the start of a flight number: CA in CA818.
    iata    VARCHAR(2)  NOT NULL,
    -- Three-letter ICAO designator, used by air traffic control: CCA in CCA818.
    icao    VARCHAR(3)  NOT NULL,
    name    VARCHAR(60) NOT NULL,
    -- Name in Chinese, where there is a common one.
    name_zh VARCHAR(60),
    -- Other names people use for the airline, in any language.
    aliases TEXT[]      NOT NULL DEFAULT '{}',

    CONSTRAINT airlines_pkey     PRIMARY KEY (iata),
    CONSTRAINT airlines_icao_key UNIQUE (icao)
);

